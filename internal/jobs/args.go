// Package jobs defines every background job's arguments. Areas enqueue by args type and
// the owning area registers the worker (see internal/app). River runs them on Postgres.
package jobs

import "github.com/google/uuid"

// Queues.
const (
	QueueDefault  = "default"
	QueueEmail    = "email"
	QueueWebhooks = "webhooks"
)

// SendMessageArgs sends an outbound email reply (messages.delivery_status = pending). Owner: email.
type SendMessageArgs struct {
	WorkspaceID uuid.UUID `json:"workspace_id"`
	MessageID   uuid.UUID `json:"message_id"`
}

func (SendMessageArgs) Kind() string { return "email.send_message" }

// SendTicketEmailArgs sends a non-message email from the ticket's mailbox to its contact
// (auto-reply, CSAT request). Owner: email.
type SendTicketEmailArgs struct {
	WorkspaceID uuid.UUID `json:"workspace_id"`
	TicketID    uuid.UUID `json:"ticket_id"`
	Subject     string    `json:"subject"`
	HTML        string    `json:"html"`
	Text        string    `json:"text"`
	// AutoGenerated marks the mail Auto-Submitted so other autoresponders ignore it.
	AutoGenerated bool `json:"auto_generated"`
}

func (SendTicketEmailArgs) Kind() string { return "email.send_ticket_email" }

// ProcessInboundArgs parses a stored raw email into a ticket message. Owner: email.
type ProcessInboundArgs struct {
	WorkspaceID    uuid.UUID `json:"workspace_id"`
	InboundEmailID uuid.UUID `json:"inbound_email_id"`
}

func (ProcessInboundArgs) Kind() string { return "email.process_inbound" }

// SyncMailboxArgs fetches new mail for an IMAP/OAuth mailbox. Owner: email.
type SyncMailboxArgs struct {
	MailboxID uuid.UUID `json:"mailbox_id"`
}

func (SyncMailboxArgs) Kind() string { return "email.sync_mailbox" }

// Ticket triggers.
const (
	TriggerTicketCreated   = "ticket_created"
	TriggerCustomerReplied = "customer_replied"
	TriggerAgentReplied    = "agent_replied"
	TriggerTicketUpdated   = "ticket_updated"
)

// TicketTriggerArgs runs SLA assignment, automations, auto-assignment and notifications
// after a ticket changes. Owner: helpdesk.
type TicketTriggerArgs struct {
	WorkspaceID uuid.UUID  `json:"workspace_id"`
	TicketID    uuid.UUID  `json:"ticket_id"`
	Trigger     string     `json:"trigger"`
	MessageID   *uuid.UUID `json:"message_id,omitempty"`
	ActorUserID *uuid.UUID `json:"actor_user_id,omitempty"`
	Changes     []string   `json:"changes,omitempty"`
}

func (TicketTriggerArgs) Kind() string { return "helpdesk.ticket_trigger" }

// WebhookDispatchArgs fans one event out to matching webhooks. Owner: core.
type WebhookDispatchArgs struct {
	WorkspaceID uuid.UUID `json:"workspace_id"`
	EventSeq    int64     `json:"event_seq"`
}

func (WebhookDispatchArgs) Kind() string { return "webhooks.dispatch" }

// WebhookDeliverArgs POSTs one delivery, retried with backoff. Owner: core.
type WebhookDeliverArgs struct {
	DeliveryID uuid.UUID `json:"delivery_id"`
}

func (WebhookDeliverArgs) Kind() string { return "webhooks.deliver" }

// SystemEmailArgs sends platform email (verification, reset, invites, notifications)
// through the system mailer. Owner: core.
type SystemEmailArgs struct {
	To      string `json:"to"`
	Subject string `json:"subject"`
	HTML    string `json:"html"`
	Text    string `json:"text"`
}

func (SystemEmailArgs) Kind() string { return "mail.system" }
